#!/usr/bin/env bash
# Vendor the Gateway API CRDs into the gateway-api cluster addon of the scs stacks.
#
# Usage: hack/update-gateway-api-crds.sh <gateway-api-version> <stack-dir>...
#   hack/update-gateway-api-crds.sh v1.4.1 providers/openstack/scs/1-35 providers/docker/scs/1-35
#   hack/update-gateway-api-crds.sh v1.6.3 providers/openstack/scs/1-36
#
# The CRDs are those the Cilium Gateway API support needs: the standard channel
# plus TLSRoute, which the hosted control plane provider uses for TLS
# passthrough (experimental channel before Gateway API v1.5, standard channel
# since then). Pick the Gateway API version that the Cilium version of the cni
# addon supports, see
# https://docs.cilium.io/en/stable/network/servicemesh/gateway-api/gateway-api/
#
# Cilium 1.19: Gateway API v1.4.1, Cilium 1.20: Gateway API v1.6.3

set -euo pipefail

cd "$(dirname "$0")/.."

if [[ $# -lt 2 || "$1" != v* ]]; then
    echo "Usage: $0 <gateway-api-version, e.g. v1.4.1> <stack-dir>..." >&2
    exit 1
fi

VERSION="$1"
shift

BASE="https://raw.githubusercontent.com/kubernetes-sigs/gateway-api/${VERSION}/config/crd"

# TLSRoute is part of the standard channel since Gateway API v1.5, before that only the experimental channel has it
tlsroute_channel=experimental
if [[ "$(printf '%s\n' v1.5.0 "$VERSION" | sort -V | head -n1)" == "v1.5.0" ]]; then
    tlsroute_channel=standard
fi

CRDS=(
    standard/gateway.networking.k8s.io_gatewayclasses.yaml
    standard/gateway.networking.k8s.io_gateways.yaml
    standard/gateway.networking.k8s.io_grpcroutes.yaml
    standard/gateway.networking.k8s.io_httproutes.yaml
    standard/gateway.networking.k8s.io_referencegrants.yaml
    "${tlsroute_channel}/gateway.networking.k8s.io_tlsroutes.yaml"
)

targets=()
for dir in "$@"; do targets+=("${dir%/}/cluster-addon/gateway-api"); done

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

out="$tmp/crds.yaml"
{
    echo "# Gateway API CRDs ${VERSION} (standard channel, TLSRoute from the ${tlsroute_channel} channel)."
    echo "# Generated by hack/update-gateway-api-crds.sh, do not edit."
} > "$out"

for crd in "${CRDS[@]}"; do
    echo "Fetching ${crd}" >&2
    {
        echo "---"
        curl -fsSL "${BASE}/${crd}"
    } >> "$out"
done

# The file is rendered by helm template, a literal {{ would be interpreted
if grep -q '{{' "$out"; then
    echo "CRDs contain '{{', rendering them as a template would fail" >&2
    exit 1
fi

for target in "${targets[@]}"; do
    mkdir -p "$target/templates"
    cp "$tmp/crds.yaml" "$target/templates/crds.yaml"
    cat > "$target/Chart.yaml" <<EOF
apiVersion: v2
type: application
description: Gateway API CRDs ${VERSION}
name: gateway-api
version: v1
appVersion: ${VERSION}
EOF
    echo "Updated ${target} (${VERSION})" >&2
done
